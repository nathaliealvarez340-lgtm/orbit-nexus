import type {
  InvoiceValidationIssue,
  InvoiceValidationSection,
} from "@/types/invoice-studio";
import type { Cfdi40Issue } from "./errors";

// Fase 5C.4: CFDI 4.0 content issues expressed in Invoice Studio's published validation
// contract (InvoiceValidationIssue), so READY and the CFDI builder share one set of rules.
// Codes are namespaced "CFDI_<code>"; messages are the curated ones, with the official
// matrix rule when there is one.

const attributeFields: Record<string, string> = {
  ClaveProdServ: "productCode",
  ClaveUnidad: "unitCode",
  Descripcion: "description",
  Cantidad: "quantity",
  ValorUnitario: "unitPrice",
  Descuento: "discount",
  ObjetoImp: "taxObject",
  Moneda: "currency",
  TipoCambio: "exchangeRate",
  FormaPago: "paymentForm",
  MetodoPago: "paymentMethod",
  Exportacion: "exportCode",
  TipoDeComprobante: "documentType",
  UsoCFDI: "cfdiUse",
  Rfc: "rfc",
  Nombre: "legalName",
  RegimenFiscal: "fiscalRegime",
  RegimenFiscalReceptor: "fiscalRegime",
  DomicilioFiscalReceptor: "postalCode",
  LugarExpedicion: "postalCode",
};

function section(path: string): InvoiceValidationSection {
  if (path.includes("/Conceptos")) return "concepts";
  if (path.includes("/Emisor") || /@(LugarExpedicion|Fecha)$/.test(path))
    return "issuer";
  if (path.includes("/Receptor")) return "receiver";
  if (/@(FormaPago|MetodoPago)$/.test(path)) return "payment";
  if (/@(SubTotal|Descuento|Total)$/.test(path) || path.includes("/Impuestos"))
    return "totals";
  return "document";
}

function field(issue: Cfdi40Issue) {
  const { path } = issue;
  // Fecha is generated by the server; only the draft-date mismatch points at a user field.
  if (issue.code === "ISSUE_DATE_DIFFERS_FROM_DRAFT") return "invoiceDate";
  if (
    /\/Traslado(\[\d+\])?\/@TasaOCuota$|\/Traslados$/.test(path) &&
    path.includes("/Conceptos")
  )
    return "vatRate";
  const attribute = /@([A-Za-z]+)$/.exec(path)?.[1];
  return attribute ? attributeFields[attribute] : undefined;
}

export function cfdi40ReadinessIssues(
  issues: readonly Cfdi40Issue[],
): InvoiceValidationIssue[] {
  return issues.map((issue) => {
    const concept = /Concepto\[(\d+)\]/.exec(issue.path);
    const target = field(issue);
    return {
      code: "CFDI_" + issue.code,
      severity: "ERROR",
      section: section(issue.path),
      ...(target ? { field: target } : {}),
      ...(concept ? { conceptIndex: Number(concept[1]) - 1 } : {}),
      message: /^CFDI\d+$/.test(issue.rule)
        ? `${issue.message} (${issue.rule})`
        : issue.message,
    };
  });
}
