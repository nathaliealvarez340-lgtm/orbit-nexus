import cfdiUses from "@/lib/sat/catcfdi/c_UsoCFDI.json";
import paymentForms from "@/lib/sat/catcfdi/c_FormaPago.json";
import paymentMethods from "@/lib/sat/catcfdi/c_MetodoPago.json";
import currencies from "@/lib/sat/catcfdi/c_Moneda.json";
import documentTypes from "@/lib/sat/catcfdi/c_TipoDeComprobante.json";
import exportCodes from "@/lib/sat/catcfdi/c_Exportacion.json";
import taxObjects from "@/lib/sat/catcfdi/c_ObjetoImp.json";
import taxes from "@/lib/sat/catcfdi/c_Impuesto.json";
import factors from "@/lib/sat/catcfdi/c_TipoFactor.json";
import rates from "@/lib/sat/catcfdi/c_TasaOCuota.json";
import { postalCodeIndex, type PostalCodeEntry } from "@/lib/sat/postal-codes";

// Fase 5C.4: lookups over the official, versioned catCFDI resources only
// (src/lib/sat/catcfdi, generated by scripts/sat/build-catcfdi.mjs from the official xls and
// verified against catCFDI.xsd). No curated subsets. The large catalogs load lazily, once.

export type Validity = { validFrom: string | null; validTo: string | null };
export type PersonType = "INDIVIDUAL" | "COMPANY";
export type CatalogLookup<T extends Validity = Validity> = (
  code: string,
) => T | undefined;
export type TaxRateEntry = Validity & {
  kind: "FIXED" | "RANGE";
  tax: string;
  taxLabel: string;
  factor: string;
  min: string;
  max: string;
  transfer: boolean;
  withholding: boolean;
};
/** c_ClaveProdServ flags: S = Sí, O = Opcional, N = No. */
export type ProductEntry = Validity & {
  includeVat: "S" | "O" | "N";
  includeIeps: "S" | "O" | "N";
  complement: string;
  borderStimulus: boolean;
};

export interface Cfdi40Catalogs {
  readonly release: string;
  regime: CatalogLookup<Validity & { personTypes: readonly PersonType[] }>;
  cfdiUse: CatalogLookup<
    Validity & {
      personTypes: readonly PersonType[];
      receiverRegimes: readonly string[];
    }
  >;
  paymentForm: CatalogLookup;
  paymentMethod: CatalogLookup;
  currency: CatalogLookup<Validity & { decimals: number }>;
  documentType: CatalogLookup;
  exportCode: CatalogLookup;
  taxObject: CatalogLookup;
  tax: CatalogLookup<Validity & { withholding: boolean; transfer: boolean }>;
  factor: CatalogLookup;
  readonly rates: readonly TaxRateEntry[];
  product: CatalogLookup<ProductEntry>;
  /** Enumerated by catCFDI.xsd but absent from the official xls: no validity data. */
  productInXsdOnly(code: string): boolean;
  unit: CatalogLookup;
  unitInXsdOnly(code: string): boolean;
  postalCode(code: string): PostalCodeEntry | undefined;
}

/** In force on an ISO date (YYYY-MM-DD); both official bounds are inclusive. */
export const inForce = (entry: Validity, date: string) =>
  (!entry.validFrom || entry.validFrom <= date) &&
  (!entry.validTo || entry.validTo >= date);

const byCode = <T extends { code: string }>(entries: readonly T[]) => {
  const map = new Map(entries.map((e) => [e.code, e]));
  return (code: string) => map.get(code);
};
const xsdOnly = (catalog: "c_ClaveProdServ" | "c_ClaveUnidad") => {
  const codes = new Set(manifest.catalogs[catalog].verification.xsdOnlyCodes);
  return (code: string) => codes.has(code);
};
const date = (value: string) => value || null;

let loaded: Promise<Cfdi40Catalogs> | undefined;
async function load(): Promise<Cfdi40Catalogs> {
  const [productData, unitData, postalCodes] = await Promise.all([
    import("@/lib/sat/catcfdi/c_ClaveProdServ.json"),
    import("@/lib/sat/catcfdi/c_ClaveUnidad.json"),
    postalCodeIndex(),
  ]);
  const products = new Map<string, ProductEntry>();
  for (const row of productData.default.entries as string[]) {
    const [code, vat, ieps, complement, from, to, stimulus] = row.split("|");
    products.set(code, {
      includeVat: vat as ProductEntry["includeVat"],
      includeIeps: ieps as ProductEntry["includeIeps"],
      complement,
      validFrom: date(from),
      validTo: date(to),
      borderStimulus: stimulus === "1",
    });
  }
  const units = new Map<string, Validity>();
  for (const row of unitData.default.entries as string[]) {
    const [code, from, to] = row.split("|");
    units.set(code, { validFrom: date(from), validTo: date(to) });
  }
  return {
    release: manifest.release,
    regime: byCode(
      regimes.entries as (Validity & {
        code: string;
        personTypes: PersonType[];
      })[],
    ),
    cfdiUse: byCode(
      cfdiUses.entries as (Validity & {
        code: string;
        personTypes: PersonType[];
        receiverRegimes: string[];
      })[],
    ),
    paymentForm: byCode(paymentForms.entries),
    paymentMethod: byCode(paymentMethods.entries),
    currency: byCode(currencies.entries),
    documentType: byCode(documentTypes.entries),
    exportCode: byCode(exportCodes.entries),
    taxObject: byCode(taxObjects.entries),
    tax: byCode(taxes.entries),
    factor: byCode(factors.entries),
    rates: rates.entries as TaxRateEntry[],
    product: (code) => products.get(code),
    productInXsdOnly: xsdOnly("c_ClaveProdServ"),
    unit: (code) => units.get(code),
    unitInXsdOnly: xsdOnly("c_ClaveUnidad"),
    postalCode: (code) => postalCodes.get(code),
  };
}

/** Official catalogs for this process (resolves once). */
export function loadCfdi40Catalogs() {
  return (loaded ??= load());
}
