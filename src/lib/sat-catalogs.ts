// c_RegimenFiscal and c_UsoCFDI come from the official, versioned catCFDI resources
// (src/lib/sat/catcfdi, generated by scripts/sat/build-catcfdi.mjs). Never edit by hand.
const regimeEntries: OfficialRegime[] = regimeData.entries as OfficialRegime[];
const cfdiUseEntries: OfficialCfdiUse[] =
  cfdiUseData.entries as OfficialCfdiUse[];
const today = () => new Date().toISOString().slice(0, 10);
/** In force on the given ISO date (YYYY-MM-DD) according to the official validity dates. */
export function inForce(
  entry: { validFrom: string | null; validTo: string | null },
  date = today(),
) {
  return (
    (!entry.validFrom || entry.validFrom <= date) &&
    (!entry.validTo || entry.validTo >= date)
  );
}
// Official descriptions end with a period in some catalogs; labels drop it for display.
const label = (description: string) => description.replace(/\.\s*$/, "");

export const officialRegimes = new Map(regimeEntries.map((r) => [r.code, r]));
export const fiscalRegimeCatalog = regimeEntries.map((r) =>
  inForce(r)
    ? on(r.code, label(r.description))
    : off(r.code, label(r.description)),
);
export const regimePersonTypes = new Map(
  regimeEntries.map((r) => [r.code, r.personTypes]),
);

export const officialCfdiUses = new Map(cfdiUseEntries.map((u) => [u.code, u]));
// CP01 (Pagos) and CN01 (Nómina) belong to complements outside Fase 5.
const unsupportedUses = new Set(["CP01", "CN01"]);
export const cfdiUseCatalog = cfdiUseEntries.map((u) =>
  inForce(u) && !unsupportedUses.has(u.code)
    ? on(u.code, label(u.description))
    : off(u.code, label(u.description)),
);
export const cfdiUseRules = new Map(
  cfdiUseEntries.map((u) => [
    u.code,
    { personTypes: u.personTypes, receiverRegimes: u.receiverRegimes },
  ]),
);
