/** "0.160000" -> "0.16", "0.0" -> "0"; string-based so rates never pass through floats. */
export function canonicalRate(value: string) {
  return value.includes(".")
    ? value.replace(/0+$/, "").replace(/\.$/, "")
    : value;
}
