// Fase 5C.2 §9: HTTP security headers, applied by next.config.ts. Pure and env-driven so
// they can be tested. next.config headers are resolved at build time: the build
// environment (Vercel injects VERCEL_ENV) decides HSTS and upgrade-insecure-requests.
type Env = Record<string, string | undefined>;
type Header = { key: string; value: string };
export type HeaderRule = { source: string; headers: Header[] };

/** HTTPS deployment: Vercel production/preview, or an explicit https auth origin. */
export function servedOverHttps(env: Env) {
  return (
    env.VERCEL_ENV === "production" ||
    env.VERCEL_ENV === "preview" ||
    /^https:\/\//.test(env.BETTER_AUTH_URL ?? "")
  );
}

/**
 * Page CSP. No third-party origin is allowed: ORBIT loads no external scripts, fonts
 * (next/font self-hosts them), images or analytics. 'unsafe-eval' exists only in
 * development (React debugging). 'unsafe-inline' remains for scripts and styles: Next
 * inlines its bootstrap scripts and removing it needs a per-request nonce, which makes
 * every page dynamic (documented debt, FASE5C2-CONTRACT §9).
 */
export function contentSecurityPolicy(env: Env) {
  const development = env.NODE_ENV === "development";
  return [
    "default-src 'self'",
    `script-src 'self' 'unsafe-inline'${development ? " 'unsafe-eval'" : ""}`,
    "style-src 'self' 'unsafe-inline'",
    // blob: previews of selected tickets; data: inline images generated by the UI.
    "img-src 'self' blob: data:",
    "font-src 'self'",
    `connect-src 'self'${development ? " ws: wss:" : ""}`,
    // Ticket capture shows the camera stream.
    "media-src 'self' blob: mediastream:",
    "worker-src 'self'",
    "manifest-src 'self'",
    "frame-src 'none'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    ...(servedOverHttps(env) ? ["upgrade-insecure-requests"] : []),
  ].join("; ");
}

/** API responses are data: nothing in them may execute, render or be framed. */
export const apiContentSecurityPolicy =
  "default-src 'none'; frame-ancestors 'none'; sandbox";

export function securityHeaders(env: Env = process.env): HeaderRule[] {
  const common: Header[] = [
    { key: "Content-Security-Policy", value: contentSecurityPolicy(env) },
    { key: "X-Content-Type-Options", value: "nosniff" },
    { key: "X-Frame-Options", value: "DENY" },
    { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
    {
      key: "Permissions-Policy",
      value:
        "camera=(self), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()",
    },
    { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
    { key: "X-Permitted-Cross-Domain-Policies", value: "none" },
    // Only the production HTTPS deployment; subdomains and preload need a domain decision.
    ...(env.VERCEL_ENV === "production"
      ? [{ key: "Strict-Transport-Security", value: "max-age=63072000" }]
      : []),
  ];
  const privateHeaders: Header[] = [
    { key: "Cache-Control", value: "private, no-store" },
    { key: "Referrer-Policy", value: "no-referrer" },
    { key: "Cross-Origin-Resource-Policy", value: "same-origin" },
  ];
  // When several rules set the same header, the last matching rule wins.
  return [
    { source: "/:path*", headers: common },
    {
      source: "/api/:path*",
      headers: [
        { key: "Content-Security-Policy", value: apiContentSecurityPolicy },
        ...privateHeaders,
      ],
    },
    { source: "/dashboard/:path*", headers: privateHeaders },
  ];
}
